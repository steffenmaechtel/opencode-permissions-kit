#!/usr/bin/env python3
"""Generate internal/reviews/INDEX.md from the case folders.

One row per case (pr-NNNNN): key, stem/subject, scope, base, started,
snapshots, status. Data sources, in order:

1. the mandatory review-meta header in review-a.md (new cases), and
2. the frozen legacy-index.md stem map (pre-restructure corpus).

Usage: python3 scripts/gen-review-index.py   (from the repo root)
Writes internal/reviews/INDEX.md. Hand edits are pointless — the parity
test (tests/unit/test-reviews-parity.sh) regenerates and compares.
Stdlib only.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REVIEWS = os.path.join(ROOT, 'internal', 'reviews')
META_FIELDS = ('ID', 'Snapshot', 'Subject', 'Scope', 'Base', 'Diff',
               'Date', 'Reviewer')
META_RE = re.compile(r'<!--\s*review-meta\s*\n(.*?)-->', re.S)
FIELD_RE = re.compile(r'^([A-Za-z]+):\s*(.+)$', re.M)
LEGACY_ROW_RE = re.compile(
    r'^\|\s*(pr-\d{5})\s*\|\s*v(\d+\.\d+\.\d+)\s*\|\s*(\d{4}-\d{2}-\d{2})\s*\|')


def read(path):
    with open(path, encoding='utf-8') as fh:
        return fh.read()


def parse_meta(text):
    m = META_RE.search(text)
    if not m:
        return None
    out = {}
    for key, val in FIELD_RE.findall(m.group(1)):
        out[key] = val.strip()
    missing = [f for f in META_FIELDS if f not in out]
    return None if missing else out


def parse_legacy():
    """Frozen stem map in legacy-index.md → {key: (stem, started)}."""
    table = {}
    path = os.path.join(REVIEWS, 'legacy-index.md')
    if not os.path.exists(path):
        return table
    for line in read(path).splitlines():
        m = LEGACY_ROW_RE.match(line)
        if m:
            table[m.group(1)] = ('v' + m.group(2), m.group(3))
    return table


def letters(folder):
    out = []
    for f in sorted(glob.glob(os.path.join(folder, 'review-*.md'))):
        m = re.match(r'review-([a-z]+)\.md$', os.path.basename(f))
        if m:
            out.append(m.group(1))
    return out


def span(ls):
    return ls[0] if len(ls) == 1 else '%s–%s' % (ls[0], ls[-1])


def status(folder, meta):
    res = os.path.join(folder, 'resolution.md')
    if meta and os.path.exists(res):
        m = re.search(r'^Status:\s*(\w+)', read(res), re.M)
        if m:
            return m.group(1).lower()
        return 'open'
    if not meta and os.path.exists(res):
        return 'resolved'   # legacy chains all closed pre-restructure
    return 'no-resolution'


def main():
    legacy = parse_legacy()
    rows = []
    for folder in sorted(glob.glob(os.path.join(REVIEWS, 'pr-*'))):
        if not os.path.isdir(folder):
            continue
        key = os.path.basename(folder)
        meta = None
        first = os.path.join(folder, 'review-a.md')
        if os.path.exists(first):
            meta = parse_meta(read(first))
        ls = letters(folder)
        if meta:
            stem, started = meta.get('Subject', ''), meta.get('Date', '')
            scope, base = meta.get('Scope', '—'), meta.get('Base', '—')
            rid = meta.get('ID', key)
            if rid != key:
                print('WARN %s: header ID %s != folder' % (key, rid),
                      file=sys.stderr)
        elif key in legacy:
            stem, started = legacy[key]
            scope, base = 'legacy', '—'
        else:
            stem, started, scope, base = '?', '?', '?', '?'
        rows.append((key, stem, scope, base, started, span(ls),
                     status(folder, meta)))
    lines = [
        '# INDEX — review cases',
        '',
        '<!-- GENERATED by scripts/gen-review-index.py — do not edit.',
        'The parity test regenerates and compares. -->',
        '',
        '| Key | Stem / Subject | Scope | Base | Started | Snapshots | Status |',
        '|---|---|---|---|---|---|---|',
    ]
    for r in rows:
        lines.append('| %s | %s | %s | %s | %s | %s | %s |' % r)
    lines.append('')
    out = os.path.join(REVIEWS, 'INDEX.md')
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('INDEX.md: %d cases' % len(rows))


if __name__ == '__main__':
    main()
